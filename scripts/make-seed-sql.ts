// Writes supabase/seed.sql from the same data the demo uses (src/lib/seed.ts), so the two never drift.
// Appointment dates are relative to the Monday of the week you run the seed in.
import { writeFileSync } from "node:fs";
import { buildSeed, DEMO_WEEK_START } from "../src/lib/seed";
import { toMinutes } from "../src/lib/time";

const q = (s: string | undefined) => (s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);
const s = buildSeed();
const rel = (dt: string) => {
  const days = Math.round((toMinutes(`${dt.slice(0, 10)}T00:00`) - toMinutes(`${DEMO_WEEK_START}T00:00`)) / 1440);
  return `wk() + ${days} + time '${dt.slice(11, 16)}'`;
};
export function seedSql(): string {
  const L: string[] = [];
  L.push("-- Generated by `npm run seed:sql` from src/lib/seed.ts. Do not edit by hand.");
  L.push("-- Staff rows are created without logins: see the README for linking them to Supabase Auth users.");
  L.push("set app.seeding = 'on';");
  L.push("create or replace function wk() returns date language sql stable as $$ select date_trunc('week', (now() at time zone 'Europe/Tirane'))::date $$;");
  L.push("");
  L.push("insert into chairs (id, name) values " + s.chairs.map((c) => `(${q(c.id)}, ${q(c.name)})`).join(", ") + ";");
  L.push("insert into staff (id, name, role, title, email, active, hours, default_chair) values");
  L.push(s.staff.map((x) => `  (${q(x.id)}, ${q(x.name)}, ${q(x.role)}, ${q(x.title)}, ${q(x.email)}, ${x.active}, ${x.hours ? q(JSON.stringify(x.hours)) + "::jsonb" : "null"}, ${q(x.defaultChair)})`).join(",\n") + ";");
  L.push("insert into treatments (id, name, minutes, price_all, performed_by) values");
  L.push(s.treatments.map((t) => `  (${q(t.id)}, ${q(t.name)}, ${t.minutes}, ${t.priceAll}, ${q(t.by)})`).join(",\n") + ";");
  L.push("insert into patients (id, name, phone, dob, dentist_id) values");
  L.push(s.patients.map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.phone)}, ${q(p.dob)}, ${q(p.dentistId)})`).join(",\n") + ";");
  L.push("insert into appointments (id, patient_id, dentist_id, chair_id, treatment_id, starts_at, ends_at, status, cancel_reason, created_by) values");
  L.push(s.appointments.map((a) => `  (${q(a.id)}, ${q(a.patientId)}, ${q(a.dentistId)}, ${q(a.chairId)}, ${q(a.treatmentId)}, ${rel(a.start)}, ${rel(a.end)}, ${q(a.status)}, ${q(a.cancelReason)}, ${q(a.createdBy)})`).join(",\n") + ";");
  L.push("insert into notes (id, patient_id, author_id, at, text) values");
  L.push(s.notes.map((n) => `  (${q(n.id)}, ${q(n.patientId)}, ${q(n.authorId)}, ${rel(n.at)}, ${q(n.text)})`).join(",\n") + ";");
  L.push("drop function wk();");
  L.push("reset app.seeding;");
  return L.join("\n") + "\n";
}
if (process.argv[1]?.endsWith("make-seed-sql.ts")) {
  writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seedSql());
  console.log("wrote supabase/seed.sql");
}
